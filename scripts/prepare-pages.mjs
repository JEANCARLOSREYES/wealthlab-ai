/** Package a verified static build for standard GitHub Pages /docs publishing. */
import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'dist-pages'),
  target = path.join(root, 'docs');
await stat(path.join(source, 'index.html'));
try {
  await stat(target);
  await readFile(path.join(target, '.wealthlab-generated'));
  await rm(target, { recursive: true });
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  try {
    await stat(target);
    throw new Error('docs/ exists without the generated marker. Move your files before packaging.');
  } catch (check) {
    if (check.code !== 'ENOENT') throw check;
  }
}
await mkdir(target, { recursive: true });
await cp(source, target, { recursive: true });
await writeFile(path.join(target, '.nojekyll'), '');
await writeFile(
  path.join(target, '.wealthlab-generated'),
  'Generated by scripts/prepare-pages.mjs. Edit src/ and rebuild.\n',
);
console.log('GitHub Pages package ready in docs/.');
